GROUP_ORDER = ["ستون فقرات", "اندام فوقانی", "اندام تحتانی", "عصبی", "سایر"]


def seed_lists(conn) -> None:
    from . import db as dbm

    now = dbm.now_iso()
    for label, grp in BODY_PARTS:
        conn.execute("INSERT OR IGNORE INTO body_parts(label, grp, source, created_at)"
                     " VALUES(?,?, 'seed', ?)", (label.strip(), grp, now))
    for label in TREATMENTS:
        conn.execute("INSERT OR IGNORE INTO treatments(label, source, created_at)"
                     " VALUES(?, 'seed', ?)", (label.strip(), now))


def fetch_grouped(conn) -> list[dict]:
    rows = conn.execute("SELECT * FROM body_parts ORDER BY CASE grp"
                        " WHEN 'ستون فقرات' THEN 0 WHEN 'اندام فوقانی' THEN 1"
                        " WHEN 'اندام تحتانی' THEN 2 WHEN 'عصبی' THEN 3 ELSE 4 END,"
                        " used_count DESC, label").fetchall()
    groups: dict[str, list] = {}
    for r in rows:
        groups.setdefault(r["grp"], []).append(dict(r))
    ordered = [k for k in GROUP_ORDER if k in groups] + [k for k in groups if k not in GROUP_ORDER]
    return [{"grp": k, "items": groups[k]} for k in ordered]


def fetch_treatments(conn) -> list[dict]:
    return [dict(r) for r in conn.execute(
        "SELECT * FROM treatments ORDER BY used_count DESC, label").fetchall()]


def list_of(conn, table: str) -> list[dict]:
    return [dict(r) for r in conn.execute(f"SELECT * FROM {table} ORDER BY label").fetchall()]
